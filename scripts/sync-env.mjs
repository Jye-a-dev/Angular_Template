import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');
const envPath = path.join(rootDir, '.env');

function parseEnvFile(filePath) {
  if (!fs.existsSync(filePath)) {
    return {};
  }
  const content = fs.readFileSync(filePath, 'utf-8');
  const result = {};
  for (const line of content.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eqIdx = trimmed.indexOf('=');
    if (eqIdx !== -1) {
      const key = trimmed.slice(0, eqIdx).trim();
      const val = trimmed
        .slice(eqIdx + 1)
        .trim()
        .replace(/^['"]|['"]$/g, '');
      result[key] = val;
    }
  }
  return result;
}

function loadEnvironmentVariables() {
  if (typeof process.loadEnvFile === 'function') {
    try {
      process.loadEnvFile(envPath);
    } catch {
      const parsed = parseEnvFile(envPath);
      for (const [key, val] of Object.entries(parsed)) {
        if (!process.env[key]) {
          process.env[key] = val;
        }
      }
    }
  } else {
    const parsed = parseEnvFile(envPath);
    for (const [key, val] of Object.entries(parsed)) {
      if (!process.env[key]) {
        process.env[key] = val;
      }
    }
  }
}

loadEnvironmentVariables();

const apiBaseUrl = process.env.NG_API_BASE_URL || 'http://localhost:8000/api';
const envDir = path.join(rootDir, 'src', 'environments');

if (!fs.existsSync(envDir)) {
  fs.mkdirSync(envDir, { recursive: true });
}

const prodEnvContent = `// Auto-generated by scripts/sync-env.mjs - do not edit directly
export const environment = {
  production: true,
  apiBaseUrl: '${apiBaseUrl}',
};
`;

const devEnvContent = `// Auto-generated by scripts/sync-env.mjs - do not edit directly
export const environment = {
  production: false,
  apiBaseUrl: '${apiBaseUrl}',
};
`;

fs.writeFileSync(path.join(envDir, 'environment.ts'), prodEnvContent, 'utf-8');
fs.writeFileSync(path.join(envDir, 'environment.development.ts'), devEnvContent, 'utf-8');

console.log(`[sync-env] Environment synchronized with API Base URL: ${apiBaseUrl}`);
